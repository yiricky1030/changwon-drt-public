CREATE TABLE IF NOT EXISTS transport.dim_transit_stop (
  stop_id text PRIMARY KEY, service_id text, stop_name text NOT NULL,
  direction text, longitude double precision, latitude double precision,
  master_dong_value text, source_created_at date, source_modified_at date,
  geometry geometry(Point, 4326), source text, loaded_at timestamptz NOT NULL,
  dataset_version text NOT NULL
);
CREATE TABLE IF NOT EXISTS transport.fact_stop_ridership (
  record_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  stop_id text REFERENCES transport.dim_transit_stop(stop_id),
  service_date date, hour integer CHECK (hour BETWEEN 0 AND 23),
  ridership integer CHECK (ridership IS NULL OR ridership >= 0),
  is_duplicate_observation boolean NOT NULL,
  duplicate_group_size integer NOT NULL CHECK (duplicate_group_size >= 1),
  source text, loaded_at timestamptz NOT NULL, dataset_version text NOT NULL
);
CREATE TABLE IF NOT EXISTS transport.curated_stop_profile (
  stop_id text PRIMARY KEY REFERENCES transport.dim_transit_stop(stop_id),
  stop_name text, direction text, longitude double precision, latitude double precision,
  geometry geometry(Point, 4326), observation_start date, observation_end date,
  observation_days integer, total_ridership bigint, avg_daily_ridership double precision,
  weekday_ridership bigint, weekend_ridership bigint, morning_ridership bigint,
  daytime_ridership bigint, evening_ridership bigint, late_night_ridership bigint,
  peak_hour integer, peak_hour_ridership bigint, missing_observation_count integer,
  duplicate_observation_count integer, has_duplicate_observations boolean,
  quality_status text, is_analysis_ready boolean,
  source text, generated_at timestamptz, dataset_version text NOT NULL
);
